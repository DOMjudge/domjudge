<?php declare(strict_types=1);

namespace App\Entity;

use Doctrine\ORM\Mapping as ORM;

/**
 * Output of a single pass of a judging run.
 *
 * Split off from JudgingRunPass so that listing the passes of a run does not
 * drag in all of their output, in the same way that JudgingRunOutput is split
 * off from JudgingRun.
 *
 * All of these are truncated to the `output_storage_limit` by the judgedaemon,
 * just like the output of the run itself.
 */
#[ORM\Entity]
#[ORM\Table(options: [
    'collation' => 'utf8mb4_unicode_ci',
    'charset' => 'utf8mb4',
    'comment' => 'Stores output of a single pass of a judging run',
])]
#[ORM\Index(name: 'passid', columns: ['passid'])]
class JudgingRunPassOutput
{
    /**
     * We use a ManyToOne instead of a OneToOne here, because otherwise the
     * reverse of this relation will always be loaded. See the commit message of commit
     * 9e421f96691ec67ed62767fe465a6d8751edd884 for a more elaborate explanation.
     */
    #[ORM\Id]
    #[ORM\ManyToOne(inversedBy: 'output')]
    #[ORM\JoinColumn(name: 'passid', referencedColumnName: 'passid', onDelete: 'CASCADE')]
    private JudgingRunPass $pass;

    /**
     * The input this pass was run with, i.e. the `nextpass.in` the validator
     * produced during the previous pass. NULL for the first pass, which runs on
     * the input of the testcase itself.
     */
    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Input generated by the validator for this pass']
    )]
    private ?string $input = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Output of running the program']
    )]
    private ?string $output_run = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Diffing the program output and testcase output']
    )]
    private ?string $output_diff = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Standard error output of the program']
    )]
    private ?string $output_error = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Judging system output']
    )]
    private ?string $output_system = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Judging metadata of the run']
    )]
    private ?string $metadata = null;

    #[ORM\Column(
        type: 'blobtext',
        nullable: true,
        options: ['comment' => 'Judging metadata of the validator']
    )]
    private ?string $validatorMetadata = null;

    public function setPass(JudgingRunPass $pass): JudgingRunPassOutput
    {
        $this->pass = $pass;
        return $this;
    }

    public function getPass(): JudgingRunPass
    {
        return $this->pass;
    }

    public function setInput(?string $input): JudgingRunPassOutput
    {
        $this->input = $input;
        return $this;
    }

    public function getInput(): ?string
    {
        return $this->input;
    }

    public function setOutputRun(?string $outputRun): JudgingRunPassOutput
    {
        $this->output_run = $outputRun;
        return $this;
    }

    public function getOutputRun(): ?string
    {
        return $this->output_run;
    }

    public function setOutputDiff(?string $outputDiff): JudgingRunPassOutput
    {
        $this->output_diff = $outputDiff;
        return $this;
    }

    public function getOutputDiff(): ?string
    {
        return $this->output_diff;
    }

    public function setOutputError(?string $outputError): JudgingRunPassOutput
    {
        $this->output_error = $outputError;
        return $this;
    }

    public function getOutputError(): ?string
    {
        return $this->output_error;
    }

    public function setOutputSystem(?string $outputSystem): JudgingRunPassOutput
    {
        $this->output_system = $outputSystem;
        return $this;
    }

    public function getOutputSystem(): ?string
    {
        return $this->output_system;
    }

    public function setMetadata(?string $metadata): JudgingRunPassOutput
    {
        $this->metadata = $metadata;
        return $this;
    }

    public function getMetadata(): ?string
    {
        return $this->metadata;
    }

    public function setValidatorMetadata(?string $validatorMetadata): JudgingRunPassOutput
    {
        $this->validatorMetadata = $validatorMetadata;
        return $this;
    }

    public function getValidatorMetadata(): ?string
    {
        return $this->validatorMetadata;
    }
}
